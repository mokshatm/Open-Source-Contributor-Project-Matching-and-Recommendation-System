import "server-only";
import { Pool } from "pg";

const globalDatabase = globalThis;

export function getDatabasePool() {
  if (!process.env.DATABASE_URL) {
    const error = new Error("PostgreSQL is not configured. Set DATABASE_URL to enable contribution tracking.");
    error.status = 503;
    throw error;
  }
  if (!globalDatabase.osMatcherPostgresPool) {
    globalDatabase.osMatcherPostgresPool = new Pool({ connectionString: process.env.DATABASE_URL, max: 8 });
  }
  return globalDatabase.osMatcherPostgresPool;
}

export async function ensureContributionSchema() {
  if (!globalDatabase.osMatcherContributionSchema) {
    globalDatabase.osMatcherContributionSchema = getDatabasePool().query(`
      CREATE TABLE IF NOT EXISTS contribution_issues (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        owner_username TEXT NOT NULL,
        title TEXT NOT NULL DEFAULT '',
        repository_url TEXT NOT NULL,
        issue_url TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'Saved' CHECK (status IN ('Saved', 'In Progress', 'PR Submitted', 'Merged')),
        pr_url TEXT,
        personal_notes TEXT NOT NULL DEFAULT '',
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        UNIQUE (owner_username, issue_url)
      );
      ALTER TABLE contribution_issues ADD COLUMN IF NOT EXISTS title TEXT NOT NULL DEFAULT '';
      CREATE INDEX IF NOT EXISTS contribution_issues_owner_updated_idx
        ON contribution_issues (owner_username, updated_at DESC);
      CREATE UNIQUE INDEX IF NOT EXISTS contribution_issues_owner_id_unique_idx
        ON contribution_issues (owner_username, id);
      CREATE TABLE IF NOT EXISTS community_interactions (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        owner_username TEXT NOT NULL,
        organization TEXT NOT NULL DEFAULT '',
        interaction_type TEXT NOT NULL,
        interaction_link TEXT NOT NULL,
        interaction_date DATE NOT NULL,
        notes TEXT NOT NULL DEFAULT '',
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE INDEX IF NOT EXISTS community_interactions_owner_date_idx
        ON community_interactions (owner_username, interaction_date DESC);
      CREATE TABLE IF NOT EXISTS project_milestones (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        owner_username TEXT NOT NULL,
        project_phase TEXT NOT NULL,
        title TEXT NOT NULL,
        start_date DATE,
        end_date DATE,
        notes TEXT NOT NULL DEFAULT '',
        sequence_order INTEGER NOT NULL DEFAULT 0,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        UNIQUE (owner_username, id)
      );
      CREATE INDEX IF NOT EXISTS project_milestones_owner_timeline_idx
        ON project_milestones (owner_username, start_date, sequence_order);
      CREATE TABLE IF NOT EXISTS milestone_contributions (
        owner_username TEXT NOT NULL,
        milestone_id BIGINT NOT NULL,
        contribution_id BIGINT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        PRIMARY KEY (owner_username, milestone_id, contribution_id),
        FOREIGN KEY (owner_username, milestone_id) REFERENCES project_milestones(owner_username, id) ON DELETE CASCADE,
        FOREIGN KEY (owner_username, contribution_id) REFERENCES contribution_issues(owner_username, id) ON DELETE CASCADE
      );
    `).catch((error) => {
      globalDatabase.osMatcherContributionSchema = null;
      throw error;
    });
  }
  await globalDatabase.osMatcherContributionSchema;
  return getDatabasePool();
}
